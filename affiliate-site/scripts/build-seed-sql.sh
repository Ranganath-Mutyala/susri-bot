#!/usr/bin/env bash
# Regenerates seed/seed.sql (starter content for Cloudflare D1) from prisma/seed.ts.
# Requires the sqlite3 CLI. Only needed if you change the starter content in prisma/content/.
set -euo pipefail
cd "$(dirname "$0")/.."
TMP_DB="$(mktemp -u /tmp/seed-XXXXXX).db"
export DATABASE_URL="file:$TMP_DB"
npx prisma migrate deploy >/dev/null
npx tsx prisma/seed.ts

# Prisma's file engine stores DateTime as epoch milliseconds, but the D1 adapter
# reads and writes ISO-8601 text. Convert so seeded rows match rows written on Cloudflare.
iso() { echo "UPDATE \"$1\" SET \"$2\" = strftime('%Y-%m-%dT%H:%M:%f+00:00', \"$2\" / 1000.0, 'unixepoch') WHERE typeof(\"$2\") = 'integer';"; }
sqlite3 "$TMP_DB" "
$(iso Setting updatedAt)
$(iso Page updatedAt)
$(iso LandingPage createdAt) $(iso LandingPage updatedAt)
$(iso Article createdAt) $(iso Article updatedAt) $(iso Article publishedAt)
$(iso Lead createdAt)
$(iso ContactMessage createdAt)
$(iso OfferLink updatedAt)
"
{
  echo "-- Starter content for Cloudflare D1. Generated by scripts/build-seed-sql.sh — do not edit by hand."
  echo "-- INSERT OR IGNORE: safe to run repeatedly; never overwrites content you edited in /admin."
  sqlite3 "$TMP_DB" .dump \
    | grep -E '^INSERT INTO' \
    | grep -vE '_prisma_migrations|INTO "?sqlite_' \
    | sed 's/^INSERT INTO/INSERT OR IGNORE INTO/'
} > seed/seed.sql
rm -f "$TMP_DB" "$TMP_DB-journal"
echo "Wrote seed/seed.sql ($(grep -c '^INSERT' seed/seed.sql) rows)"
