/**
 * Writes a D1 migration that updates the live compliance pages from prisma/content/pages.ts.
 * Usage: npx tsx scripts/build-pages-migration.ts migrations/000N_name.sql [slug,slug] [--pages-only]
 *   slug list: only update these pages (default: all four)
 *   --pages-only: don't touch settings or landing pages
 */
import { writeFileSync } from "node:fs";
import { pages } from "../prisma/content/pages";

const out = process.argv[2];
if (!out) throw new Error("Pass the output file, e.g. migrations/0002_update_compliance_pages.sql");

const only = process.argv[3] && !process.argv[3].startsWith("--") ? process.argv[3].split(",") : null;
const pagesOnly = process.argv.includes("--pages-only");
const selected = only ? pages.filter((p) => only.includes(p.slug)) : pages;
if (only && selected.length !== only.length) throw new Error(`Unknown slug in: ${only.join(",")}`);

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const now = "strftime('%Y-%m-%dT%H:%M:%f+00:00','now')"; // same text format the Prisma D1 adapter uses

const sql = [
  "-- Generated by scripts/build-pages-migration.ts from prisma/content/pages.ts",
  `-- Updates pages: ${selected.map((p) => p.slug).join(", ")}${pagesOnly ? "" : "; business address; unpublishes sample offers"}.`,
  ...selected.map(
    (p) =>
      `UPDATE "Page" SET "title" = ${q(p.title)}, "metaDescription" = ${q(p.metaDescription)}, "content" = ${q(p.content)}, "updatedAt" = ${now} WHERE "slug" = ${q(p.slug)};`,
  ),
  ...(pagesOnly ? [] : [
  `UPDATE "Setting" SET "contactAddress" = ${q("Ranganath Mutyala\nHyderabad, Telangana, India")}, "contactEmail" = ${q("hello@wisecompareguide.com")}, "updatedAt" = ${now} WHERE "id" = 1;`,
  `UPDATE "LandingPage" SET "status" = 'draft', "updatedAt" = ${now} WHERE "slug" IN ('best-ai-meeting-assistant', 'credit-monitoring-service', 'compare-home-insurance-quotes');`,
  ]),
  "",
].join("\n");

writeFileSync(out, sql);
console.log(`Wrote ${out}`);
